(async () => { try {
  await sl(600);
  const L = window.__ls;
  ok(!!L, 'hooks');
  tap($q('#lsItem')); await sl(100);
  ok(!$q('#lsPop').hidden, 'popover opens');
  ok($q('#pCpu').textContent.includes('%'), 'popover has CPU ' + $q('#pCpu').textContent);
  ok($q('#pBarsP').children.length === 6 && $q('#pBarsE').children.length === 4, 'core bars');
  tap($q('#pSettings')); await sl(100);
  ok($q('#lsPop').hidden, 'popover closes');
  ok(!$q('[data-win="settings"]').hidden, 'settings opens');
  tap($q('#setRows .ls-lt[data-l="perCore"]')); await sl(50);
  ok(L.SET().metrics[0].layout === 'perCore', 'cpu per-core');
  tap($q('#setLook [data-v="colored"]')); await sl(50);
  ok(L.SET().color === 'colored', 'colored');
  tap($q('#setRows [data-kind="ram"] [data-act="up"]')); await sl(50);
  ok(L.SET().metrics[1].kind === 'ram', 'ram moved up');
  tap($q('#setRows [data-kind="gpu"] [data-act="toggle"]')); await sl(50);
  ok(!L.SET().metrics.find(m => m.kind === 'gpu').enabled, 'gpu hidden');
  tap($q('#setRate [data-v="5"]')); await sl(50);
  ok(L.SET().interval === 5, 'interval 5');
  tap($q('#tRun')); await sl(50);
  ok(L.WORK.build, 'build running');
  tap($q('#expBtn')); await sl(50);
  ok(L.WORK.exportOn, 'export running');
  for (let i = 0; i < 12; i++) { tap($q('#newTab')); }
  ok(L.WORK.tabs === 13, 'tabs ' + L.WORK.tabs);
  await sl(600);
  ok(L.shown().ram >= 0.8, 'ram high ' + L.shown().ram.toFixed(2));
  ok(L.shown().cores.slice(0, 6).every(c => c > 0.8), 'p-cores busy');
  ok(L.shown().gpu > 0.8, 'gpu busy');
  const sw = L.M.wins.get('safari'), x0 = sw.x;
  await drag($q('[data-win="safari"] .mk-bar span').parentElement, -80, 30);
  ok(Math.abs(sw.x - x0) > 20, 'window drags ' + (sw.x - x0).toFixed(0));
  tap($q('[data-win="term"] .mk-bar i[data-a="close"]')); await sl(50);
  ok($q('[data-win="term"]').hidden, 'close button');
  tap($q('.mk-dk[data-dk="term"]')); await sl(50);
  ok(!$q('[data-win="term"]').hidden, 'dock reopens');
  pe($q('[data-menu="apple"]'), 'pointerdown'); await sl(50);
  ok(!!$q('.mk-menu'), 'apple menu');
  const about = [...document.querySelectorAll('.mk-menu .mk-mi')].find(m => m.textContent.includes('About This Mac'));
  about.click(); await sl(50);
  ok(!$q('[data-win="about"]').hidden && !$q('.mk-menu'), 'about window');
  tap($q('#lsItem')); await sl(50); tap($q('#pQuit')); await sl(50);
  ok($q('#lsItem').hidden && !$q('[data-work="relaunch"]').hidden, 'quit');
  $q('[data-work="relaunch"]').click(); await sl(50);
  ok(!$q('#lsItem').hidden, 'relaunch');
  ok($q('#qCount').textContent === '8 / 8', 'quests ' + $q('#qCount').textContent);
  ok(document.documentElement.scrollWidth <= innerWidth, 'no h-scroll ' + document.documentElement.scrollWidth);
  // a Show me run
  $q('#qReset').click(); await sl(100);
  $q('[data-show="style"]').click(); await sl(2500);
  ok(L.SET().metrics[0].layout === 'perCore', 'show me style');
} catch (e) { ok(false, 'EXC ' + e.message); } finish(); })();
