(async () => { try {
  await sl(500);
  const L = window.__ld, strip = $q('#strip');
  const tiles = [...strip.querySelectorAll('.ld-t')];
  const r0 = tiles[0].getBoundingClientRect(), r1 = tiles[tiles.length - 1].getBoundingClientRect();
  for (let i = 0; i <= 10; i++) pe(strip, 'pointermove', r0.left + (r1.right - r0.left) * i / 10, r0.top + 5);
  ok(L.Q.has('magnify'), 'magnify quest');
  pe(strip.querySelector('[data-app="terminal"]'), 'pointerdown'); await sl(50);
  ok(L.running.has('terminal') && !$q('[data-win="terminal"]').hidden, 'launch terminal');
  ok(strip.querySelector('[data-app="terminal"]').classList.contains('run'), 'running dot');
  pe(strip.querySelector('[data-app="downloads"]'), 'pointerdown'); await sl(30);
  const items = [...document.querySelectorAll('.mk-ui > .mk-menu .mk-mi')];
  ok(items.length === 9, 'downloads stack ' + items.length);
  items.pop().click(); await sl(30);
  ok(L.Q.has('downloads') && !$q('[data-win="finder"]').hidden, 'open downloads');
  pe(strip.querySelector('[data-app="safari"]'), 'pointerdown', null, null, { button: 2 }); await sl(30);
  [...document.querySelectorAll('.mk-ui > .mk-menu .mk-mi')].find(m => m.textContent.includes('Settings')).click(); await sl(50);
  ok(!$q('[data-win="settings"]').hidden, 'settings via right-click');
  $q('#ldSet [data-act="add"]').click(); await sl(30);
  const add = [...document.querySelectorAll('.mk-ui > .mk-menu .mk-mi')].find(m => m.textContent.includes('Xcode')); add.click(); await sl(30);
  ok(L.P().apps.includes('xcode') && strip.querySelector('[data-app="xcode"]'), 'added xcode');
  const row = $q('#ldApps .ld-app[data-i="0"]'), rr = row.getBoundingClientRect();
  pe(row, 'pointerdown', rr.left + 60, rr.top + rr.height / 2);
  for (let i = 1; i <= 6; i++) pe($q('#ldSet'), 'pointermove', rr.left + 60, rr.top + rr.height / 2 + i * rr.height * 0.4);
  pe($q('#ldSet'), 'pointerup', rr.left + 60, rr.top + rr.height * 3);
  ok(L.P().apps[0] !== 'safari', 'drag reorder ' + L.P().apps.join(','));
  const sz = $q('#ldSet [data-p="size"]'); sz.value = 16; sz.dispatchEvent(new Event('input', { bubbles: true }));
  ok(L.P().size === 16 && strip.style.getPropertyValue('--sz') === '12.8px', 'icon size slider');
  $q('#ldDockBox [data-act="hide"]').click(); await sl(50);
  pe($q('#ldAct [data-k]'), 'pointerdown'); await sl(20);
  pe($q('#ldAct [data-k]'), 'pointerdown'); await sl(900);
  ok(L.dockHidden() && L.M.dockEl.classList.contains('away'), 'dock hidden via terminal');
  $q('[data-win="safari"] .mk-bar i[data-a="zoom"]').click(); await sl(30);
  const sw = L.M.wins.get('safari'); ok(sw.y + sw.h >= L.M.H - 1, 'full height ' + (sw.y + sw.h) + '/' + L.M.H);
  ok($q('#qCount').textContent === '7 / 7', 'quests ' + $q('#qCount').textContent);
  ok(document.documentElement.scrollWidth <= innerWidth, 'no h-scroll');
  $q('#qReset').click(); await sl(100);
  ok(!L.dockHidden(), 'reset shows dock');
  $q('[data-show="hide"]').click(); await sl(5000);
  ok(L.dockHidden(), 'show me hide');
} catch (e) { ok(false, 'EXC ' + e.message); } finish(); })();
